// Builds the test catalog from the same scenario table the tests execute.
//   node scripts/export-catalog.js
// Writes testcases/catalog.json and testcases/TEST_CASES.md.
import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { scenarios, toCatalogEntry } from '../test/scenarios.js';
import { planned } from '../test/planned.js';

const outDir = fileURLToPath(new URL('../testcases/', import.meta.url));
mkdirSync(outDir, { recursive: true });

const catalog = [...scenarios.map(toCatalogEntry), ...planned];
writeFileSync(`${outDir}catalog.json`, JSON.stringify(catalog, null, 2) + '\n');

// Summary table by area.
const byArea = new Map();
for (const c of catalog) {
  const row = byArea.get(c.area) ?? { automated: 0, planned: 0, allow: 0, deny: 0 };
  row[c.status] += 1;
  if (c.expected === 'allow') row.allow += 1;
  if (c.expected === 'deny') row.deny += 1;
  byArea.set(c.area, row);
}

const lines = [];
lines.push('# HIWONET-RESPONSE — Test Case Catalog');
lines.push('');
lines.push('Generated by `npm run catalog` from `test/scenarios.js` and `test/planned.js`. Do not edit by hand.');
lines.push('');
lines.push(`Total: **${catalog.length}** cases — **${scenarios.length}** automated (security rules), **${planned.length}** planned (Cloud Functions).`);
lines.push('');
lines.push('| Area | Automated | Planned | Expect allow | Expect deny |');
lines.push('|---|---:|---:|---:|---:|');
for (const [area, r] of byArea) {
  lines.push(`| ${area} | ${r.automated} | ${r.planned} | ${r.allow} | ${r.deny} |`);
}
lines.push('');

for (const area of byArea.keys()) {
  lines.push(`## ${area}`);
  lines.push('');
  const rows = catalog.filter((c) => c.area === area);
  if (rows[0].status === 'automated') {
    lines.push('| ID | Scenario | Actor | Operation | Target | Expected |');
    lines.push('|---|---|---|---|---|---|');
    for (const c of rows) {
      lines.push(`| ${c.id} | ${c.title} | ${c.actor} | ${c.operation} | \`${c.target}\` | ${c.expected} |`);
    }
  } else {
    lines.push('| ID | Scenario | Expected |');
    lines.push('|---|---|---|');
    for (const c of rows) lines.push(`| ${c.id} | ${c.title} | ${c.expected} |`);
  }
  lines.push('');
}

writeFileSync(`${outDir}TEST_CASES.md`, lines.join('\n'));
console.log(`Catalog written: ${catalog.length} cases (${scenarios.length} automated, ${planned.length} planned).`);
